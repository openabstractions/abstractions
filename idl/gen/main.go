package main

import (
	"fmt"
	"io"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

type backend struct {
	lang      string
	path      string
	emit      func(*Definition) string
	imports   []string
	emitsCode bool
}

// comment is the marker each language's own tooling looks for. Go's exact form
// is fixed by convention and matched by a regexp in the standard toolchain, so
// the wording of every other language follows it rather than inventing one.
var comment = map[string]string{"go": "//", "cpp": "//", "javascript": "//", "rust": "//", "python": "#"}

// origin is the definition named the same way from any working directory, so
// two runs of the generator produce the same bytes.
func origin(path string) string {
	parts := strings.Split(filepath.ToSlash(path), "/")
	if len(parts) > 2 {
		parts = parts[len(parts)-2:]
	}
	return strings.Join(parts, "/")
}

func banner(lang, path, body string) string {
	c, ok := comment[lang]
	if !ok {
		return body
	}
	return c + " Code generated by abstraction-idl from " + origin(path) + ". DO NOT EDIT.\n\n" + body
}

type emitted struct {
	def     *Definition
	lang    string
	imports []string
	body    string
	source  string
	// whole is this backend over the definition entire. A selection may not
	// weaken a check by removing the code it examines, so the checks that ask
	// what a backend can say ask it of this and not of body.
	whole string
}

func (b backend) verify(e emitted) error {
	if b.emitsCode {
		return verifyCode(e)
	}
	return verifyDocs(e)
}

var backends = []backend{
	{"go", "go/rec/rec.go", genGo, nil, true},
	{"python", "py/_codec.py", genPy, []string{"__future__", "dataclasses", "enum"}, true},
	{"cpp", "cpp/rec.h", genCpp, []string{
		"cstddef", "cstdint", "map", "optional", "stdexcept", "string", "string_view", "vector"}, true},
	{"javascript", "js/internal.mjs", genJS, nil, true},
	{"rust", "rs/rec.rs", genRust, []string{"std::collections::BTreeMap"}, true},
	{"docs", "schema.html", genDocs, nil, false},
}

// publicModules are the modules an application imports, beside a backend's
// implementation module: Python's package __init__.py and JavaScript's
// index.mjs. Each re-exports the implementation's public names and nothing else.
var publicModules = map[string]struct {
	file string
	emit func(*Definition, string) string
}{
	"python":     {"__init__.py", genPyPublic},
	"javascript": {"index.mjs", genJSPublic},
}

// jsTypesPath is index.d.mts, the TypeScript declarations TypeScript pairs with index.mjs.
func jsTypesPath(path string) string {
	return filepath.ToSlash(filepath.Join(filepath.Dir(path), "index.d.mts"))
}

// publicPath is where a backend's public module lands beside its implementation.
func publicPath(lang, path string) (string, bool) {
	m, ok := publicModules[lang]
	if !ok {
		return "", false
	}
	return filepath.ToSlash(filepath.Join(filepath.Dir(path), m.file)), true
}

const usage ="usage: gen <definition.thrift> <outdir> [-only=<surface,...>] [--no-ipc] [--shared-rust-transport] [language ...]\n       gen <definition.thrift> --paths [language ...]"

func main() {
	if err := run(os.Args[1:], os.Stdout); err != nil {
		fail(err)
	}
}

func run(args []string, stdout io.Writer) error {
	if len(args) == 0 || len(args) == 1 && (args[0] == "--help" || args[0] == "-h") {
		fmt.Fprintln(stdout, usage)
		fmt.Fprintln(stdout, "Languages: go python cpp javascript rust docs. Omit languages for all backends.")
		fmt.Fprintln(stdout, "--no-ipc emits service interfaces and record types/codecs without IPC bindings (Go, C++, Python, Rust).")
		fmt.Fprintln(stdout, "--shared-rust-transport uses the pure abstraction-frame crate for Rust IPC; standalone and --no-ipc outputs remain independent.")
		fmt.Fprintln(stdout, "--go-alias-package=import-path emits Go compatibility exports forwarding to the canonical generated package.")
		fmt.Fprintln(stdout, "--named-codecs exports composable per-record codecs; generate dependencies with this flag.")
		fmt.Fprintln(stdout, "--go-import=alias=package-path maps an include filename alias to its generated Go package; repeat per dependency.")
		fmt.Fprintln(stdout, "--js-import=alias=module-specifier maps an include filename alias to its generated JavaScript module or package; repeat per dependency.")
		fmt.Fprintln(stdout, "--rust-import=alias=crate-path maps an include filename alias to the Rust crate holding its generated records; repeat per dependency.")
		fmt.Fprintln(stdout, "--paths lists output locations without generating code or claiming backend support for a schema's features.")
		fmt.Fprintln(stdout, "Run the generator and its tests with GOWORK=off (PowerShell: $env:GOWORK=\"off\") so a surrounding go.work does not replace this module.")
		fmt.Fprintln(stdout, "Tests: GOWORK=off go test ./... ; Python-backed tests use PYTHON, else python on PATH, and need a real interpreter (on Windows the Store python alias fails; see idl/test/production/README.md).")
		return nil
	}
	if len(args) < 2 {
		return fmt.Errorf("%s", usage)
	}
	whole, err := loadDefinition(args[0])
	if err != nil {
		return fmt.Errorf("%s: %w", args[0], err)
	}
	namespaceLanguages := make([]string, 0, len(whole.Namespaces))
	for lang := range whole.Namespaces {
		namespaceLanguages = append(namespaceLanguages, lang)
	}
	sort.Strings(namespaceLanguages)
	for _, lang := range namespaceLanguages {
		if err := validateNamespace(lang, whole.Namespaces[lang]); err != nil {
			return err
		}
	}
	var want, only []string
	goAlias := ""
	noIPC := false
	for _, a := range args[2:] {
		switch {
		case strings.HasPrefix(a, "--go-alias-package="):
			value := strings.TrimPrefix(a, "--go-alias-package=")
			if goAlias != "" || value == "" || strings.ContainsAny(value, "\"\\ \n\r\t") {
				return fmt.Errorf("--go-alias-package requires one nonempty import path")
			}
			goAlias = value
		case a == "--shared-rust-transport":
			if whole.SharedRustTransport {
				return fmt.Errorf("--shared-rust-transport may be supplied once")
			}
			whole.SharedRustTransport = true
		case a == "--named-codecs":
			whole.NamedCodecs = true
		case strings.HasPrefix(a, "--go-import="):
			pair := strings.SplitN(strings.TrimPrefix(a, "--go-import="), "=", 2)
			if len(pair) != 2 || pair[0] == "" || pair[1] == "" || strings.ContainsAny(pair[1], "\"\\ \n\r") {
				return fmt.Errorf("--go-import requires alias=package-path")
			}
			if whole.GoImports == nil {
				whole.GoImports = map[string]string{}
			}
			if whole.GoImports[pair[0]] != "" {
				return fmt.Errorf("duplicate Go import mapping %s", pair[0])
			}
			whole.GoImports[pair[0]] = pair[1]
		case strings.HasPrefix(a, "--js-import="):
			pair := strings.SplitN(strings.TrimPrefix(a, "--js-import="), "=", 2)
			if len(pair) != 2 || pair[0] == "" || !jsModuleSpecifier(pair[1]) {
				return fmt.Errorf("--js-import requires alias=module-specifier")
			}
			if whole.JSImports == nil {
				whole.JSImports = map[string]string{}
			}
			if whole.JSImports[pair[0]] != "" {
				return fmt.Errorf("duplicate JavaScript import mapping %s", pair[0])
			}
			whole.JSImports[pair[0]] = pair[1]
		case strings.HasPrefix(a, "--rust-import="):
			pair := strings.SplitN(strings.TrimPrefix(a, "--rust-import="), "=", 2)
			if len(pair) != 2 || pair[0] == "" || !rustCratePath.MatchString(pair[1]) {
				return fmt.Errorf("--rust-import requires alias=crate-path")
			}
			if whole.RustImports == nil {
				whole.RustImports = map[string]string{}
			}
			if whole.RustImports[pair[0]] != "" {
				return fmt.Errorf("duplicate Rust import mapping %s", pair[0])
			}
			whole.RustImports[pair[0]] = pair[1]
		case a == "--no-ipc":
			if noIPC {
				return fmt.Errorf("--no-ipc may be supplied once")
			}
			noIPC = true
		case strings.HasPrefix(a, "-only="):
			if only != nil {
				return fmt.Errorf("-only may be supplied once")
			}
			only = strings.Split(strings.TrimPrefix(a, "-only="), ",")
			for i, n := range only {
				only[i] = strings.TrimSpace(n)
			}
			if len(only) == 1 && only[0] == "" {
				return fmt.Errorf("-only names nothing; leave the flag off to emit every surface")
			}
		case strings.HasPrefix(a, "-"):
			return fmt.Errorf("%s is not a flag this generator takes\n%s", a, usage)
		default:
			known := false
			for _, b := range backends {
				known = known || b.lang == a
			}
			if !known {
				return fmt.Errorf("no backend named %s", a)
			}
			if contains(want, a) {
				return fmt.Errorf("backend %s was requested twice", a)
			}
			want = append(want, a)
		}
	}
	def, err := selected(whole, only)
	if err != nil {
		return fmt.Errorf("%s: %w", args[0], err)
	}
	if noIPC {
		if def.Proto != nil {
			return fmt.Errorf("--no-ipc requires service declarations; legacy protocol-only interface generation is not implemented")
		}
		copy := *def
		copy.NoIPC = true
		def = &copy
	}
	out := args[1]
	if out == "--paths" {
		for _, b := range backends {
			if len(want) > 0 && !contains(want, b.lang) {
				continue
			}
			path, _ := namespacedOutput(b, def.Namespaces, "")
			fmt.Fprintln(stdout, path)
			if public, ok := publicPath(b.lang, path); ok {
				fmt.Fprintln(stdout, public)
			}
			if b.lang == "javascript" {
				fmt.Fprintln(stdout, jsTypesPath(path))
			}
		}
		return nil
	}
	type artifact struct{ path, body, report string }
	var artifacts []artifact
	// Validate and render the entire request before changing any output. A
	// misspelt or unsupported backend must not leave a plausible partial build.
	for _, b := range backends {
		if len(want) > 0 && !contains(want, b.lang) {
			continue
		}
		if err := validateIncludes(def, b.lang); err != nil {
			return err
		}
		if err := validateBinaryBackend(def, b.lang); err != nil {
			return err
		}
		if err := validateServiceBackend(def, b.lang); err != nil {
			return err
		}
	}
	for _, b := range backends {
		if len(want) > 0 && !contains(want, b.lang) {
			continue
		}
		body := emitIncluded(b, def)
		entire := body
		if def != whole {
			verificationDefinition := whole
			if validateServiceBackend(whole, b.lang) != nil {
				// An explicitly selected record-only artifact still checks all
				// declared refusal words, including the service frame's grammar.
				verificationDefinition = serviceTypes(whole)
			}
			entire = emitIncluded(b, verificationDefinition)
		}
		if err := b.verify(emitted{def, b.lang, includeImports(b, def), body, args[0], entire}); err != nil {
			return err
		}
		if b.lang == "rust" {
			// Verified over every helper the backend can emit; shipped without
			// the ones this artefact never reaches, since a crate denies dead code.
			body = rsPrune(body)
		}
		path, body := namespacedOutput(b, def.Namespaces, body)
		if b.lang == "go" && goAlias != "" {
			body, err = goExportAliases(body, goAlias)
			if err != nil {
				return err
			}
		}
		if public, ok := publicPath(b.lang, path); ok {
			text := banner(b.lang, args[0], publicModules[b.lang].emit(def, body))
			artifacts = append(artifacts, artifact{public, text,
				fmt.Sprintf("%-12s %-16s %5d lines  %s\n", b.lang, public, strings.Count(text, "\n"), "public names")})
		}
		if b.lang == "javascript" {
			decl, err := genJSTypes(def, body)
			if err != nil {
				return err
			}
			typesPath := jsTypesPath(path)
			text := banner(b.lang, args[0], decl)
			artifacts = append(artifacts, artifact{typesPath, text,
				fmt.Sprintf("%-12s %-16s %5d lines  %s\n", b.lang, typesPath, strings.Count(text, "\n"), "declarations")})
		}
		body = banner(b.lang, args[0], body)
		artifacts = append(artifacts, artifact{path, body,
			fmt.Sprintf("%-12s %-16s %5d lines  %s\n", b.lang, path, strings.Count(body, "\n"), carries(whole, def))})
	}
	for _, a := range artifacts {
		p := filepath.Join(out, a.path)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(p, []byte(a.body), 0o644); err != nil {
			return err
		}
		fmt.Fprint(stdout, a.report)
	}
	return nil
}

func carries(whole, def *Definition) string {
	all := surfaces(whole)
	if def == whole {
		return fmt.Sprintf("all %d surfaces", len(all))
	}
	got := surfaces(def)
	return fmt.Sprintf("%d of %d surfaces: %s", len(got), len(all), strings.Join(got, " "))
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "gen:", err)
	os.Exit(1)
}
