package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

type backend struct {
	lang      string
	path      string
	emit      func(*Definition) string
	imports   []string
	emitsCode bool
}

// comment is the marker each language's own tooling looks for. Go's exact form
// is fixed by convention and matched by a regexp in the standard toolchain, so
// the wording of every other language follows it rather than inventing one.
var comment = map[string]string{"go": "//", "cpp": "//", "javascript": "//", "rust": "//", "python": "#"}

// origin is the definition named the same way from any working directory, so
// two runs of the generator produce the same bytes.
func origin(path string) string {
	parts := strings.Split(filepath.ToSlash(path), "/")
	if len(parts) > 2 {
		parts = parts[len(parts)-2:]
	}
	return strings.Join(parts, "/")
}

func banner(lang, path, body string) string {
	c, ok := comment[lang]
	if !ok {
		return body
	}
	return c + " Code generated by abstraction-idl from " + origin(path) + ". DO NOT EDIT.\n\n" + body
}

type emitted struct {
	def     *Definition
	lang    string
	imports []string
	body    string
	source  string
	// whole is this backend over the definition entire. A selection may not
	// weaken a check by removing the code it examines, so the checks that ask
	// what a backend can say ask it of this and not of body.
	whole string
}

func (b backend) verify(e emitted) error {
	if b.emitsCode {
		return verifyCode(e)
	}
	return verifyDocs(e)
}

var backends = []backend{
	{"go", "go/rec/rec.go", genGo, nil, true},
	{"python", "py/rec.py", genPy, nil, true},
	{"cpp", "cpp/rec.h", genCpp, []string{
		"cstddef", "cstdint", "map", "optional", "stdexcept", "string", "string_view", "vector"}, true},
	{"javascript", "js/rec.mjs", genJS, nil, true},
	{"rust", "rs/rec.rs", genRust, []string{"std::collections::BTreeMap"}, true},
	{"docs", "schema.html", genDocs, nil, false},
}

const usage = "usage: gen <definition.thrift> <outdir> [-only=<surface,...>] [language ...]"

func main() {
	if len(os.Args) < 3 {
		fmt.Fprintln(os.Stderr, usage)
		os.Exit(2)
	}
	src, err := os.ReadFile(os.Args[1])
	if err != nil {
		fail(err)
	}
	whole, err := parse(string(src))
	if err != nil {
		fail(fmt.Errorf("%s: %w", os.Args[1], err))
	}
	var want, only []string
	for _, a := range os.Args[3:] {
		switch {
		case strings.HasPrefix(a, "-only="):
			only = strings.Split(strings.TrimPrefix(a, "-only="), ",")
			for i, n := range only {
				only[i] = strings.TrimSpace(n)
			}
			if len(only) == 1 && only[0] == "" {
				fail(fmt.Errorf("-only names nothing; leave the flag off to emit every surface"))
			}
		case strings.HasPrefix(a, "-"):
			fail(fmt.Errorf("%s is not a flag this generator takes\n%s", a, usage))
		default:
			want = append(want, a)
		}
	}
	def, err := selected(whole, only)
	if err != nil {
		fail(fmt.Errorf("%s: %w", os.Args[1], err))
	}
	out := os.Args[2]
	count := 0
	for _, b := range backends {
		if len(want) > 0 && !contains(want, b.lang) {
			continue
		}
		p := filepath.Join(out, b.path)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			fail(err)
		}
		body := b.emit(def)
		entire := body
		if def != whole {
			entire = b.emit(whole)
		}
		if err := b.verify(emitted{def, b.lang, b.imports, body, os.Args[1], entire}); err != nil {
			fail(err)
		}
		body = banner(b.lang, os.Args[1], body)
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			fail(err)
		}
		fmt.Printf("%-12s %-16s %5d lines  %s\n", b.lang, b.path, strings.Count(body, "\n"), carries(whole, def))
		count++
	}
	if count == 0 {
		fail(fmt.Errorf("no backend named %s", strings.Join(want, " ")))
	}
}

func carries(whole, def *Definition) string {
	all := surfaces(whole)
	if def == whole {
		return fmt.Sprintf("all %d surfaces", len(all))
	}
	got := surfaces(def)
	return fmt.Sprintf("%d of %d surfaces: %s", len(got), len(all), strings.Join(got, " "))
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "gen:", err)
	os.Exit(1)
}
