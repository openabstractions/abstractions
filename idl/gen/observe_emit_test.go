func TestEmissionValidLanguageCorpusUnchanged(t *testing.T) {
	base := os.Getenv("OA_OBSERVE_BASE_GENERATOR")
	if base == "" {
		t.Skip("baseline generator fixture not supplied")
	}
	for _, bound := range []string{"0..120000", "0..30000"} {
		dir := t.TempDir()
		path := filepath.Join(dir, "watch.thrift")
		header := strings.Replace(constraintHead, "  10: bad_binary       (stage = \"structure\")\n", "", 1)
		header = strings.Replace(header, "  11: bad_value", "  10: bad_value", 1)
		header = strings.Replace(header, "  12: trailing_bytes", "  11: trailing_bytes", 1)
		fixture := header + `struct Page {1:required string next}(document="true",unknown_fields="refuse")
service Watch {Page Observe(1:string cursor,2:i64 wait_ms(range="` + bound + `"))(observe="cursor")}(wire_name="test/watch@1")`
		writeNamespaceFile(t, dir, "watch.thrift", fixture)
		args := []string{path, filepath.Join(dir, "before"), "go", "python", "cpp", "javascript", "rust"}
		if output, err := exec.Command(base, args...).CombinedOutput(); err != nil {
			t.Fatalf("baseline: %v\n%s", err, output)
		}
		args[1] = filepath.Join(dir, "after")
		var report bytes.Buffer
		if err := run(args, &report); err != nil {
			t.Fatal(err)
		}
		count := 0
		files := map[string]bool{}
		err := filepath.WalkDir(filepath.Join(dir, "before"), func(path string, entry os.DirEntry, err error) error {
			if err != nil || entry.IsDir() {
				return err
			}
			relative, err := filepath.Rel(filepath.Join(dir, "before"), path)
			if err != nil {
				return err
			}
			before, err := os.ReadFile(path)
			if err != nil {
				return err
			}
			after, err := os.ReadFile(filepath.Join(dir, "after", relative))
			if err != nil {
				return err
			}
			if !bytes.Equal(before, after) {
				t.Errorf("generated bytes changed: %s", relative)
			}
			files[relative] = true
			count++
			return nil
		})
		if err != nil || count < 5 {
			t.Fatal(count, err)
		}
		if err := filepath.WalkDir(filepath.Join(dir, "after"), func(path string, entry os.DirEntry, err error) error {
			if err != nil || entry.IsDir() {
				return err
			}
			relative, err := filepath.Rel(filepath.Join(dir, "after"), path)
			if err == nil && !files[relative] {
				t.Errorf("extra generated artifact: %s", relative)
			}
			return err
		}); err != nil {
			t.Fatal(err)
		}
	}
}

func TestDirectEmitRefusesInvalidObserveRangeWithoutPanic(t *testing.T) {
	d := mustParse(t, head+`struct Page {1:required string next}(document="true",unknown_fields="refuse")
service Watch {Page Observe(1:string cursor,2:i64 wait_ms)(observe="cursor")}(wire_name="test/watch@1")`)
	for _, b := range backends {
		t.Run(b.lang, func(t *testing.T) {
			defer func() {
				if value := recover(); value != nil {
					t.Errorf("emit panicked: %v", value)
				}
			}()
			var body string
			var err error
			// Keep the regression executable against the former string-only
			// boundary so its panic is measured rather than a compile failure.
			switch emit := any(b.emit).(type) {
			case func(*Definition) string:
				body = emit(d)
			case func(*Definition) (string, error):
				body, err = emit(d)
			default:
				t.Fatal("unknown emit signature")
			}
			if err == nil || !strings.Contains(err.Error(), "requires a declared range") || body != "" {
				t.Fatalf("emit = (%q, %v)", body, err)
			}
		})
	}
}
