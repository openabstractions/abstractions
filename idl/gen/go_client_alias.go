package main

import (
	"fmt"
	"go/ast"
	"go/format"
	goparser "go/parser"
	gotoken "go/token"
	gotypes "go/types"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

type clientType struct{ path, name string }
type clientPackage struct {
	types     map[string]ast.Expr
	imports   map[string]string
	members   map[string][]string
	values    map[string]bool
	parsers   map[string]bool
	aliases   map[string]bool
	variables map[string]*ast.ValueSpec
}

func clientAliasName(name string) bool { return gotoken.IsIdentifier(name) && ast.IsExported(name) }

// goClientAliases derives the public record closure from the handwritten client
// API. The generated destination is never an input, even without its banner.
func goClientAliases(root, dir, freshPath, fresh string, retained map[string]clientType) (string, error) {
	packages := map[string]*clientPackage{}
	load := func(path string) (*clientPackage, error) {
		if p := packages[path]; p != nil {
			return p, nil
		}
		if !strings.HasPrefix(path, "github.com/openabstractions/") {
			return nil, nil
		}
		for _, part := range strings.Split(strings.TrimPrefix(path, "github.com/openabstractions/"), "/") {
			if part == "" || part == "." || part == ".." || strings.ContainsAny(part, "\\\"\r\n\t:") {
				return nil, fmt.Errorf("unsafe generated client import %q", path)
			}
		}
		var source []byte
		var err error
		if path == freshPath {
			source = []byte(fresh)
		} else {
			source, err = os.ReadFile(filepath.Join(root, "openabstractions-flat", strings.TrimPrefix(path, "github.com/openabstractions/"), "rec.go"))
			if os.IsNotExist(err) {
				return nil, nil
			}
			if err != nil {
				return nil, err
			}
			if !strings.Contains(string(source[:min(300, len(source))]), "Code generated by abstraction-idl") {
				return nil, nil
			}
		}
		f, err := goparser.ParseFile(gotoken.NewFileSet(), path, source, 0)
		if err != nil {
			return nil, err
		}
		p := &clientPackage{map[string]ast.Expr{}, map[string]string{}, map[string][]string{}, map[string]bool{}, map[string]bool{}, map[string]bool{}, map[string]*ast.ValueSpec{}}
		for _, im := range f.Imports {
			path, _ := strconv.Unquote(im.Path.Value)
			name := filepath.Base(path)
			if im.Name != nil {
				name = im.Name.Name
			}
			p.imports[name] = path
		}
		for _, d := range f.Decls {
			switch d := d.(type) {
			case *ast.GenDecl:
				var enum string
				for _, spec := range d.Specs {
					switch s := spec.(type) {
					case *ast.TypeSpec:
						p.types[s.Name.Name] = s.Type
						p.aliases[s.Name.Name] = s.Assign != 0
					case *ast.ValueSpec:
						if d.Tok == gotoken.VAR {
							for i, name := range s.Names {
								if name.IsExported() && goSharedVariable(s, i) {
									p.variables[name.Name] = s
								}
							}
						}
						if d.Tok != gotoken.CONST {
							continue
						}
						if id, ok := s.Type.(*ast.Ident); ok {
							enum = id.Name
						}
						for _, name := range s.Names {
							if name.IsExported() {
								p.members[enum] = append(p.members[enum], name.Name)
							}
						}
					}
				}
			case *ast.FuncDecl:
				if d.Recv == nil && strings.HasPrefix(d.Name.Name, "Parse") {
					p.parsers[strings.TrimPrefix(d.Name.Name, "Parse")] = true
				}
				if d.Recv == nil && strings.HasSuffix(d.Name.Name, "Values") {
					p.values[strings.TrimSuffix(d.Name.Name, "Values")] = true
				}
			}
		}
		packages[path] = p
		return p, nil
	}
	set := gotoken.NewFileSet()
	pkgs, err := goparser.ParseDir(set, dir, func(f os.FileInfo) bool { return f.Name() != "contract.go" && !strings.HasSuffix(f.Name(), "_test.go") }, 0)
	if err != nil {
		return "", err
	}
	if len(pkgs) != 1 {
		return "", fmt.Errorf("client aliases require one client package")
	}
	var files []*ast.File
	var packageName string
	for name, p := range pkgs {
		packageName = name
		for _, f := range p.Files {
			files = append(files, f)
		}
	}
	sort.Slice(files, func(i, j int) bool {
		return set.Position(files[i].Pos()).Filename < set.Position(files[j].Pos()).Filename
	})
	fileImports := map[*ast.File]map[string]string{}
	local := map[string]bool{}
	imports := map[string]string{}
	for _, f := range files {
		fi := map[string]string{}
		for _, im := range f.Imports {
			path, _ := strconv.Unquote(im.Path.Value)
			name := filepath.Base(path)
			if im.Name != nil {
				name = im.Name.Name
			}
			p, e := load(path)
			if e != nil {
				return "", e
			}
			if p != nil {
				fi[name] = path
				if imports[path] == "" {
					imports[path] = name
				}
			}
		}
		fileImports[f] = fi
		for _, d := range f.Decls {
			if d, ok := d.(*ast.GenDecl); ok {
				for _, s := range d.Specs {
					if s, ok := s.(*ast.TypeSpec); ok {
						local[s.Name.Name] = true
					}
				}
			}
		}
	}
	// A small explicit compatibility root can retain a previously published
	// alias or shared slice/map value, including qualified colliding types.
	rename := func(r clientType) string {
		for name, target := range retained {
			if target == r {
				return name
			}
		}
		return r.name
	}
	need := map[clientType]bool{}
	var visit func(clientType) error
	var collect func(ast.Node, map[string]string, string) error
	collect = func(n ast.Node, im map[string]string, own string) error {
		var failure error
		ast.Inspect(n, func(n ast.Node) bool {
			if failure != nil {
				return false
			}
			if field, ok := n.(*ast.Field); ok {
				failure = collect(field.Type, im, own)
				return false
			}
			if s, ok := n.(*ast.SelectorExpr); ok {
				if id, ok := s.X.(*ast.Ident); ok && im[id.Name] != "" {
					failure = visit(clientType{im[id.Name], s.Sel.Name})
				}
				return false
			}
			if id, ok := n.(*ast.Ident); ok {
				if own != "" {
					failure = visit(clientType{own, id.Name})
				} else if !local[id.Name] {
					var candidates []clientType
					for path, p := range packages {
						if p.types[id.Name] != nil {
							candidates = append(candidates, clientType{path, id.Name})
						}
					}
					sort.Slice(candidates, func(i, j int) bool { return candidates[i].path < candidates[j].path })
					for _, r := range candidates {
						if rename(r) == id.Name {
							failure = visit(r)
							break
						}
					}
				}
			}
			return true
		})
		return failure
	}
	visit = func(r clientType) error {
		p, e := load(r.path)
		if e != nil {
			return e
		}
		if p == nil || (p.types[r.name] == nil && p.variables[r.name] == nil) || need[r] {
			return nil
		}
		need[r] = true
		if variable := p.variables[r.name]; variable != nil {
			return collect(variable, p.imports, r.path)
		}
		return collect(p.types[r.name], p.imports, r.path)
	}
	for _, f := range files {
		for _, d := range f.Decls {
			switch d := d.(type) {
			case *ast.FuncDecl:
				if d.Name.IsExported() {
					if d.Recv != nil {
						t := d.Recv.List[0].Type
						if ptr, ok := t.(*ast.StarExpr); ok {
							t = ptr.X
						}
						if id, ok := t.(*ast.Ident); !ok || !id.IsExported() {
							continue
						}
					}
					if e := collect(d.Type, fileImports[f], ""); e != nil {
						return "", e
					}
				}
			case *ast.GenDecl:
				for _, s := range d.Specs {
					if s, ok := s.(*ast.TypeSpec); ok && s.Name.IsExported() {
						if st, ok := s.Type.(*ast.StructType); ok {
							for _, field := range st.Fields.List {
								exported := len(field.Names) == 0
								for _, name := range field.Names {
									exported = exported || name.IsExported()
								}
								if exported {
									if e := collect(field.Type, fileImports[f], ""); e != nil {
										return "", e
									}
								}
							}
							continue
						}
						if e := collect(s.Type, fileImports[f], ""); e != nil {
							return "", e
						}
					}
				}
			}
		}
		// Calls surface the generated service error even when its type is not
		// written explicitly in the facade's signatures.
		var failure error
		ast.Inspect(f, func(n ast.Node) bool {
			call, ok := n.(*ast.CallExpr)
			if !ok {
				return true
			}
			sel, ok := call.Fun.(*ast.SelectorExpr)
			if !ok {
				return true
			}
			id, ok := sel.X.(*ast.Ident)
			if !ok {
				return true
			}
			path := fileImports[f][id.Name]
			if path != "" && strings.HasPrefix(sel.Sel.Name, "New") && strings.HasSuffix(sel.Sel.Name, "Client") {
				for _, name := range []string{"ServiceError", "ServiceErrorCode"} {
					if e := visit(clientType{path, name}); e != nil {
						failure = e
					}
				}
			}
			return true
		})
		if failure != nil {
			return "", failure
		}
	}
	for name, r := range retained {
		p, e := load(r.path)
		if e != nil {
			return "", e
		}
		if p == nil || (p.types[r.name] == nil && p.variables[r.name] == nil) {
			return "", fmt.Errorf("retained client alias %s has no generated type or shared value %s.%s", name, r.path, r.name)
		}
		if e := visit(r); e != nil {
			return "", e
		}
	}
	var refs []clientType
	for r := range need {
		refs = append(refs, r)
	}
	sort.Slice(refs, func(i, j int) bool {
		if refs[i].path == refs[j].path {
			return refs[i].name < refs[j].name
		}
		return refs[i].path < refs[j].path
	})
	var declarations strings.Builder
	used := map[string]string{}
	canonical := func(r clientType) (clientType, error) {
		seen := map[clientType]bool{}
		for !seen[r] {
			seen[r] = true
			p, e := load(r.path)
			if e != nil {
				return clientType{}, e
			}
			if p == nil || !p.aliases[r.name] {
				return r, nil
			}
			switch node := p.types[r.name].(type) {
			case *ast.SelectorExpr:
				if id, ok := node.X.(*ast.Ident); ok && p.imports[id.Name] != "" {
					r = clientType{p.imports[id.Name], node.Sel.Name}
					continue
				}
			case *ast.Ident:
				if p.types[node.Name] != nil {
					r.name = node.Name
					continue
				}
				if _, ok := gotypes.Universe.Lookup(node.Name).(*gotypes.TypeName); ok {
					return clientType{"", node.Name}, nil
				}
			}
			return r, nil
		}
		return clientType{}, fmt.Errorf("cyclic generated client alias %s.%s", r.path, r.name)
	}
	claimed := map[string]clientType{}
	for _, r := range refs {
		if !ast.IsExported(r.name) {
			continue
		}
		name := rename(r)
		if target, ok := retained[name]; ok && target != r {
			continue
		}
		if local[name] {
			continue
		}
		target, e := canonical(r)
		if e != nil {
			return "", e
		}
		if previous, ok := claimed[name]; ok {
			if previous != target {
				return "", fmt.Errorf("client alias %s reaches distinct generated types %s.%s and %s.%s; retain a qualified alias", name, previous.path, previous.name, target.path, target.name)
			}
			continue
		}
		claimed[name] = target
		a := used[r.path]
		if a == "" {
			a = imports[r.path]
			if a == "" {
				a = fmt.Sprintf("contract%d", len(used))
			}
			for p, v := range used {
				if v == a && p != r.path {
					a = fmt.Sprintf("contract%d", len(used))
				}
			}
		}
		used[r.path] = a
		if packages[r.path].variables[r.name] != nil {
			fmt.Fprintf(&declarations, "var %s = %s.%s\n", name, a, r.name)
			continue
		}
		fmt.Fprintf(&declarations, "type %s = %s.%s\n", name, a, r.name)
		for _, m := range packages[r.path].members[r.name] {
			fmt.Fprintf(&declarations, "const %s = %s.%s\n", name+strings.TrimPrefix(m, r.name), a, m)
		}
		if packages[r.path].values[r.name] {
			fmt.Fprintf(&declarations, "func %sValues() []%s { return %s.%sValues() }\n", name, name, a, r.name)
		}
		if packages[r.path].parsers[r.name] {
			fmt.Fprintf(&declarations, "func Parse%s(word string) (%s,bool) { return %s.Parse%s(word) }\n", name, name, a, r.name)
		}
	}
	var paths []string
	for p := range used {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	var b strings.Builder
	fmt.Fprintf(&b, "package %s\n\nimport (\n", packageName)
	for _, p := range paths {
		fmt.Fprintf(&b, "%s %q\n", used[p], p)
	}
	b.WriteString(")\n\n")
	b.WriteString(declarations.String())
	pretty, e := format.Source([]byte(b.String()))
	return string(pretty), e
}
