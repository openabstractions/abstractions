func TestGoClientAliasesReachability(t *testing.T) {
	root := t.TempDir()
	dir := filepath.Join(root, "client")
	if err := os.MkdirAll(dir, 0755); err != nil {
		t.Fatal(err)
	}
	const path = "github.com/openabstractions/example/go/wire"
	client := `package client
import wire "github.com/openabstractions/example/go/wire"
type Public = wire.Record
type PublicFields struct { Value *wire.Record; private *wire.Unreachable }
func Read() *wire.Record { return nil }
`
	if err := os.WriteFile(filepath.Join(dir, "client.go"), []byte(client), 0644); err != nil {
		t.Fatal(err)
	}
	// A poisoned destination must neither add a root nor supply source bytes.
	if err := os.WriteFile(filepath.Join(dir, "contract.go"), []byte("package client\ntype Poison = Missing\n"), 0644); err != nil {
		t.Fatal(err)
	}
	const source = `package wire
type Record struct { Nested *Nested; State State; Private private }
type Nested struct { Leaf string }
type private = Hidden
type Hidden struct { Word string }
type State uint32
const ( StateReady State = 1; StateDone State = 2 )
func StateValues() []State { return []State{StateReady,StateDone} }
func ParseState(word string) (State,bool) { return StateReady,word=="ready" }
type Unreachable struct {}
var KnownResources = []string{"memory", "awake"}
var MutableScalar = 1
`
	body, err := goClientAliases(root, dir, path, source, nil)
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{"type Record = wire.Record", "type Nested = wire.Nested", "type Hidden = wire.Hidden", "type State = wire.State", "const StateDone = wire.StateDone", "func StateValues() []State", "func ParseState(word string) (State, bool)"} {
		if !strings.Contains(body, want) {
			t.Errorf("missing %q in:\n%s", want, body)
		}
	}
	for _, word := range []string{"Poison", "Unreachable", "type private", "type Public"} {
		if strings.Contains(body, word) {
			t.Errorf("unexpected %q in:\n%s", word, body)
		}
	}
	second, err := goClientAliases(root, dir, path, source, nil)
	if err != nil || second != body {
		t.Fatalf("unstable aliases: %v", err)
	}
	retained := map[string]clientType{"QualifiedNested": {path, "Nested"}, "Legacy": {path, "Unreachable"}}
	kept, err := goClientAliases(root, dir, path, source, retained)
	if err != nil || !strings.Contains(kept, "type QualifiedNested = wire.Nested") || !strings.Contains(kept, "type Legacy = wire.Unreachable") {
		t.Fatalf("retained aliases: %v\n%s", err, kept)
	}
	if _, err := goClientAliases(root, dir, path, source, map[string]clientType{"Missing": {path, "Missing"}}); err == nil {
		t.Fatal("unknown compatibility root accepted")
	}
	kept, err = goClientAliases(root, dir, path, source, map[string]clientType{"KnownResources": {path, "KnownResources"}})
	if err != nil || !strings.Contains(kept, "var KnownResources = wire.KnownResources") {
		t.Fatalf("retained shared value: %v\n%s", err, kept)
	}
	if _, err := goClientAliases(root, dir, path, source, map[string]clientType{"MutableScalar": {path, "MutableScalar"}}); err == nil {
		t.Fatal("mutable scalar compatibility root accepted")
	}
}

func TestGoClientAliasesNominalCollision(t *testing.T) {
	root := t.TempDir()
	const left = "github.com/openabstractions/example-left/go/wire"
	const right = "github.com/openabstractions/example-right/go/wire"
	write := func(path, source string) {
		t.Helper()
		name := filepath.Join(root, "openabstractions-flat", strings.TrimPrefix(path, "github.com/openabstractions/"), "rec.go")
		if err := os.MkdirAll(filepath.Dir(name), 0755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(name, []byte("// Code generated by abstraction-idl. DO NOT EDIT.\n"+source), 0644); err != nil {
			t.Fatal(err)
		}
	}
	write(left, "package wire\ntype Record struct{}\n")
	write(right, "package wire\ntype Record struct{}\n")
	dir := filepath.Join(root, "client")
	if err := os.MkdirAll(dir, 0755); err != nil {
		t.Fatal(err)
	}
	source := "package client\nimport (left \"" + left + "\";right \"" + right + "\")\nfunc Read(left.Record,right.Record) {}\n"
	if err := os.WriteFile(filepath.Join(dir, "client.go"), []byte(source), 0644); err != nil {
		t.Fatal(err)
	}
	if _, err := goClientAliases(root, dir, "", "", nil); err == nil || !strings.Contains(err.Error(), left+".Record") || !strings.Contains(err.Error(), right+".Record") {
		t.Fatalf("nominal collision: %v", err)
	}
	body, err := goClientAliases(root, dir, "", "", map[string]clientType{"OtherRecord": {right, "Record"}})
	if err != nil || !strings.Contains(body, "type Record = left.Record") || !strings.Contains(body, "type OtherRecord = right.Record") {
		t.Fatalf("qualified aliases: %v\n%s", err, body)
	}
	write(right, "package wire\nimport canonical \""+left+"\"\ntype Record = canonical.Record\n")
	if _, err := goClientAliases(root, dir, "", "", nil); err != nil {
		t.Fatalf("same canonical identity refused: %v", err)
	}
}

func TestGoAliasProduction(t *testing.T) {
	t.Run("ordinary", func(t *testing.T) { testGoAliasProduction(t, false) })
	t.Run("named-codecs", func(t *testing.T) { testGoAliasProduction(t, true) })
}

func testGoAliasProduction(t *testing.T, named bool) {
	t.Helper()
	root := t.TempDir()
	schema := productionFile(t, "abstraction-facade/facade.thrift")
	var out bytes.Buffer
	flags := []string{}
	if named {
		flags = append(flags, "--named-codecs")
	}
	if err := run(append([]string{schema, filepath.Join(root, "canonical"), "go"}, flags...), &out); err != nil {
		t.Fatal(err)
	}
	if err := run(append([]string{schema, filepath.Join(root, "compat"), "go", "--go-alias-package=example.test/canonical/go/abstraction/facade"}, flags...), &out); err != nil {
		t.Fatal(err)
	}
	alias, err := os.ReadFile(filepath.Join(root, "compat", "go", "abstraction", "facade", "rec.go"))
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(alias), "var Encode") || !strings.Contains(string(alias), "func Encode(") {
		t.Fatal("functions must forward")
	}
	os.WriteFile(filepath.Join(root, "go.mod"), []byte("module example.test\ngo 1.26.0\n"), 0600)
	driver := `package candidate_test
import("testing"; old "example.test/compat/go/abstraction/facade"; core "example.test/canonical/go/abstraction/facade")
func TestIdentityAndCodec(t *testing.T){
 var original core.ResolveResult = old.ResolveResult{Status:old.ResolutionStatusUnavailable}
 bytes:=old.Encode(&original); value,err:=core.Decode(bytes);if err!=nil||value.Status!=core.ResolutionStatusUnavailable{t.Fatal(value,err)}
 var _ *old.ResolverClient = core.NewResolverClient(nil)
 if old.ScopeValues()[0]!=core.ScopeValues()[0]||!old.ScopeAny.Known(){t.Fatal("vocabulary does not forward")}
}
`
	if named {
		driver += `
func TestNamedPresenceIdentityAndDepth(t *testing.T){
 v:=old.ApplicationPresence{Application:"app",Instance:"one",LeaseMs:1000}
 got:=old.EncodeApplicationPresence(&v);same:=core.EncodeApplicationPresence(&v)
 if string(got)!=string(same){t.Fatal("alias changed bytes")}
 generic,err:=core.ToJSON(&v);if err!=nil||string(got)!=string(generic)+"\n"{t.Fatal("named codec changed existing wire bytes",err)}
 value,err:=old.DecodeApplicationPresence(got);if err!=nil||value.Instance!="one"{t.Fatal(value,err)}
 if _,_,err:=old.DecodeApplicationPresenceAt(got,1,1);err==nil{t.Fatal("import depth reset")}
}
`
	}
	os.WriteFile(filepath.Join(root, "alias_test.go"), []byte(driver), 0600)
	command := exec.Command("go", "test", "./...")
	command.Dir = root
	command.Env = append(os.Environ(), "GOWORK=off")
	if result, err := command.CombinedOutput(); err != nil {
		t.Fatalf("%s: %v", result, err)
	}
}
func TestGoAliasUnsupportedAndFlags(t *testing.T) {
	if _, err := goExportAliases("package p;var Counter=1", "example/core"); err == nil {
		t.Fatal("mutable scalar silently copied")
	}
	if _, err := goExportAliases("package p;type Box[T any] struct{V T}", "example/core"); err == nil {
		t.Fatal("unsupported generic")
	}
	var out bytes.Buffer
	schema := productionFile(t, "abstraction-facade/facade.thrift")
	for _, flag := range []string{"--go-alias-package=", "--go-alias-package=bad path"} {
		if run([]string{schema, t.TempDir(), "go", flag}, &out) == nil {
			t.Fatal(flag)
		}
	}
}
