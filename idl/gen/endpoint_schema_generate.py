"""Derive the standalone compiler's base endpoint schema from its owners."""
from pathlib import Path
import argparse
import re

ROOT = Path(__file__).resolve().parents[2]


def schema(registration, facade, rights):

    def declaration(source, name):
        return re.search(r'(?ms)^(?:enum|struct) ' + name + r' \{.*?^\}[^\n]*\n', source).group()

    parts = [re.search(r'(?ms)^encoding json \{.*?^\}\n', registration).group(),
             re.search(r'(?ms)^refusal \{.*?^\}\n', registration).group()]
    for name in ['timestamp', 'Reason', 'CheckKind', 'ServiceName', 'DisplayKey', 'DisplayValue']:
        parts.append(re.search(r'(?m)^typedef .* ' + name + r'\([^\n]*\n', registration).group())
    names = ['ServiceReadiness', 'RefusalSource', 'RefusalDecision', 'RefusalAsk', 'RefusalDetail',
             'ProducerCheckState', 'ProducerCheck', 'ServiceState', 'DescriptionOutcome', 'Description']
    for name in names:
        source = facade if name == 'ServiceReadiness' else rights if name.startswith('Refusal') else registration
        parts.append(declaration(source, name))
    text = '\n'.join(parts).replace('facade.ServiceReadiness', 'ServiceReadiness').replace('rights.RefusalDetail', 'RefusalDetail')
    for name in names:
        text = re.sub(r'\b' + name + r'\b', 'Endpoint' + name, text)
    # The standalone parser needs a document root. This compiler-only marker is
    # removed before these records join a consuming service definition.
    text = text.replace('}(max_encoded="1048576",unknown_fields="grant"', '}(document="true",max_encoded="1048576",unknown_fields="grant"')
    return text


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='check the carried schema without writing it')
    parser.add_argument('--production-root', type=Path, default=ROOT / 'openabstractions-flat')
    args = parser.parse_args()
    registration = (args.production_root / 'abstraction-facade/registration.thrift').read_text(encoding='utf-8')
    facade = (args.production_root / 'abstraction-facade/facade.thrift').read_text(encoding='utf-8')
    rights = (args.production_root / 'abstraction-rights/rights.thrift').read_text(encoding='utf-8')
    text = schema(registration, facade, rights)
    depth = re.search(r'depth_limit="([0-9]+)"', rights).group(1)
    output = '// Code generated by endpoint_schema_generate.py from registration.thrift, facade.thrift and rights.thrift. DO NOT EDIT.\n\npackage main\n\nconst endpointRefusalDepthLimit = '+depth+'\n\nconst endpointSchema = `'+text+'`\n'
    target = Path(__file__).parent / 'endpoint_schema_data.go'
    if args.check:
        if target.read_text(encoding='utf-8') != output:
            raise SystemExit('endpoint base schema differs; run py -3.12 idl/gen/endpoint_schema_generate.py')
    else:
        target.write_text(output, encoding='utf-8', newline='\n')
