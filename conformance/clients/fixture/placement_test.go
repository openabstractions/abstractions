package fixture

import (
	"os"
	"path/filepath"
	"reflect"
	"runtime"
	"strings"
	"testing"

	registration "github.com/openabstractions/abstraction-facade/go/abstraction/facade/registration"
	router "github.com/openabstractions/abstraction-router/go/abstraction/router"
)

// Module dependency inversion keeps this representation out of Router's module.
// Check the real generated enums and their owning schemas at the composition.
func TestFacadePlacementMatchesRouterWireAndClosedSchema(t *testing.T) {
	facadeWords, routerWords := []string{}, []string{}
	for _, value := range registration.PlacementValues() {
		facadeWords = append(facadeWords, value.String())
	}
	for _, value := range router.PlacementValues() {
		routerWords = append(routerWords, value.String())
	}
	if !reflect.DeepEqual(facadeWords, routerWords) || !reflect.DeepEqual(facadeWords, []string{"local", "hosted", "any"}) {
		t.Fatalf("placement wire values differ: facade=%v router=%v", facadeWords, routerWords)
	}
	if _, ok := registration.ParsePlacement("future"); ok {
		t.Fatal("Facade placement accepted an unknown acting value")
	}
	if _, ok := router.ParsePlacement("future"); ok {
		t.Fatal("Router placement accepted an unknown acting value")
	}
	_, here, _, _ := runtime.Caller(0)
	root := filepath.Clean(filepath.Join(filepath.Dir(here), "../../.."))
	for _, owner := range []struct{ schema, generated, marker string }{
		{"abstraction-facade/registration.thrift", "abstraction-facade/go/abstraction/facade/registration/rec.go", "abstraction-facade/registration.thrift"},
		{"abstraction-router/router.thrift", "abstraction-router/go/abstraction/router/rec.go", "abstraction-router/router.thrift"},
	} {
		schema, err := os.ReadFile(filepath.Join(root, "openabstractions-flat", owner.schema))
		if err != nil {
			t.Fatal(err)
		}
		// This is an exact fixture assertion, not a second schema parser.
		if !strings.Contains(strings.Join(strings.Fields(string(schema)), ""), `enumPlacement{1:local2:hosted3:any}(unknown="refuse",reader="act"`) {
			t.Fatalf("%s lost the closed acting Placement provenance", owner.schema)
		}
		generated, err := os.ReadFile(filepath.Join(root, "openabstractions-flat", owner.generated))
		if err != nil {
			t.Fatal(err)
		}
		if !strings.HasPrefix(string(generated), "// Code generated by abstraction-idl from "+owner.marker+". DO NOT EDIT.") {
			t.Fatalf("%s has another schema owner", owner.generated)
		}
	}
}
